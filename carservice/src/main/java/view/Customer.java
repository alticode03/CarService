    /** Pindahkan data baris terpilih ke form (mode ubah). */
    private void mulaiUbah() {
        int row = jTable1.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Pilih customer di tabel terlebih dahulu.");
            return;
        }
        idDiedit = jTable1.getValueAt(row, 0).toString();
        jTextField1.setText(jTable1.getValueAt(row, 1).toString());
        jTextField2.setText(jTable1.getValueAt(row, 2).toString());
        jTextField3.setText(jTable1.getValueAt(row, 3).toString());

        jButton5.setText("Simpan Perubahan");
        jLabel1.setText("Ubah Customer " + idDiedit);
        jTextField1.requestFocus();
    }

    private void hapus() {
        int row = jTable1.getSelectedRow();
        if (row < 0) return;
        String id = jTable1.getValueAt(row, 0).toString();
        String nama = jTable1.getValueAt(row, 1).toString();

        int jawab = JOptionPane.showConfirmDialog(this,
                "Hapus customer " + id + " (" + nama + ")?",
                "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (jawab != JOptionPane.YES_OPTION) return;

        if (dao.hapusCustomer(id)) {
            if (id.equals(idDiedit)) resetForm();
            loadTabel();
        } else {
            JOptionPane.showMessageDialog(this,
                    "Gagal menghapus. Customer kemungkinan sudah punya transaksi.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    /** Tombol Batal: kosongkan form dan kembali ke mode tambah. */
    private void resetForm() {
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
        idDiedit = null;
        jButton5.setText("Simpan");
        jLabel1.setText("Tambah Customer Baru");
        jTable1.clearSelection();
    }

    /**
     * Form tidak punya kolom ID, jadi ID dibuat otomatis dengan format:
     * 3 huruf kapital acak + 3 angka acak, contoh: KTB482, AZM907.
     * Dicek dulu ke database agar tidak ada ID yang kembar.
     */
    private String buatIdBaru() {
        Set<String> terpakai = new HashSet<>();
        ResultSet rs = dao.tampilSemuaCustomer();
        if (rs != null) {
            try {
                while (rs.next()) {
                    terpakai.add(rs.getString("id_customer").toUpperCase());
                }
            } catch (SQLException ignored) {
            }
        }

        Random acak = new Random();
        String id;
        do {
            char huruf1 = (char) ('A' + acak.nextInt(26));
            char huruf2 = (char) ('A' + acak.nextInt(26));
            char huruf3 = (char) ('A' + acak.nextInt(26));
            id = String.format("%c%c%c%03d", huruf1, huruf2, huruf3, acak.nextInt(1000));
        } while (terpakai.contains(id));
        return id;
    }

