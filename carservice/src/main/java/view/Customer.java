     private void initLogika() {
        setTitle("Car Service - Data Customer");
        setLocationRelativeTo(null);

        // DAO dibuat sekali per form
        try {
            dao = new koneksidbc.Customer();
            koneksiOk = dao.st != null;
        } catch (Exception e) {
            koneksiOk = false;
        }
        
     DefaultTableModel model = new DefaultTableModel(
                new Object[]{"ID", "Nama Lengkap", "Nomor HP/Whatsapp", "Alamat"}, 0) {
            @Override
            public boolean isCellEditable(int row, int col) {
                return false;
            }
        };
        jTable1.setModel(model);
        jTable1.setRowHeight(24);
        jTable1.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        jTable1.getTableHeader().setReorderingAllowed(false);
        pasangMenuKlikKananTabel();
        
        // Kolom HP: hanya angka, maksimal 13 digit (huruf/simbol otomatis ditolak)
        
        ((AbstractDocument) jTextField2.getDocument()).setDocumentFilter(new DocumentFilter() {
            @Override
            public void replace(FilterBypass fb, int offset, int length,
                                String text, AttributeSet attrs) throws BadLocationException {
                if (text == null) {
                    super.replace(fb, offset, length, text, attrs);
                    return;
                }
                String angka = text.replaceAll("\\D", "");
                int sisa = 13 - (fb.getDocument().getLength() - length);
                if (sisa <= 0) return;
                if (angka.length() > sisa) angka = angka.substring(0, sisa);
                super.replace(fb, offset, length, angka, attrs);
            }

            @Override
            public void insertString(FilterBypass fb, int offset, String text,
                                     AttributeSet attr) throws BadLocationException {
                replace(fb, offset, 0, text, attr);
            }
        });

        // Kolom Cari: mencari otomatis saat mengetik (ID / nama / no HP)
        jTextField4.setToolTipText("Cari berdasarkan ID, nama, atau nomor HP");
        jTextField4.getDocument().addDocumentListener(new DocumentListener() {
            public void insertUpdate(DocumentEvent e) { if (koneksiOk) loadTabel(); }
            public void removeUpdate(DocumentEvent e) { if (koneksiOk) loadTabel(); }
            public void changedUpdate(DocumentEvent e) { }
        });

        // Tombol Simpan & Batal (di desain belum punya event)
        jButton5.addActionListener(e -> simpan());
        jButton6.addActionListener(e -> resetForm());

        // Tutup koneksi saat jendela ditutup
        addWindowListener(new WindowAdapter() {
            @Override
            public void windowClosing(WindowEvent e) {
                try {
                    if (koneksiOk) dao.st.close();
                } catch (SQLException ignored) {
                }
            }
        });

        if (koneksiOk) {
            loadTabel();
        } else {
            setFormAktif(false);
            JOptionPane.showMessageDialog(this,
                    "Koneksi database gagal. Periksa konfigurasi KoneksiJDBC.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    /** Klik kanan baris = menu Ubah/Hapus, klik ganda = Ubah. */
    private void pasangMenuKlikKananTabel() {
        JPopupMenu popup = new JPopupMenu();
        JMenuItem miUbah = new JMenuItem("Ubah");
        JMenuItem miHapus = new JMenuItem("Hapus");
        miUbah.addActionListener(e -> mulaiUbah());
        miHapus.addActionListener(e -> hapus());
        popup.add(miUbah);
        popup.add(miHapus);

        jTable1.addMouseListener(new MouseAdapter() {
            @Override
            public void mousePressed(MouseEvent e) { tampilPopup(e); }

            @Override
            public void mouseReleased(MouseEvent e) { tampilPopup(e); }

            @Override
            public void mouseClicked(MouseEvent e) {
                if (SwingUtilities.isLeftMouseButton(e) && e.getClickCount() == 2) {
                    mulaiUbah();
                }
            }

            private void tampilPopup(MouseEvent e) {
                if (e.isPopupTrigger()) {
                    int row = jTable1.rowAtPoint(e.getPoint());
                    if (row >= 0) {
                        jTable1.setRowSelectionInterval(row, row);
                        popup.show(jTable1, e.getX(), e.getY());
                    }
                }
            }
        });
    }

